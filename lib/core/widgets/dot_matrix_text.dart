class _DotMatrixPainter extends CustomPainter {
  const _DotMatrixPainter({
    required this.text,
    required this.dotSize,
    required this.dotSpacing,
    required this.charSpacing,
    required this.activeColor,
    required this.inactiveColor,
    required this.glyphs,
  });

  final String text;
  final double dotSize;
  final double dotSpacing;
  final double charSpacing;
  final Color activeColor;
  final Color? inactiveColor;
  final Map<String, List<int>> glyphs;

  @override
  void paint(Canvas canvas, Size size) {
    final activePaint =
        Paint()
          ..color = activeColor
          ..style = PaintingStyle.fill;
    final inactivePaint =
        inactiveColor != null
            ? (Paint()
              ..color = inactiveColor!
              ..style = PaintingStyle.fill)
            : null;

    final step = dotSize + dotSpacing;
    final charWidth = 5 * step - dotSpacing;
    final radius = dotSize / 2;

    for (int i = 0; i < text.length; i++) {
      final ch = text[i];
      final rows = glyphs[ch] ?? glyphs[' ']!;
      final offsetX = i * (charWidth + charSpacing);

      for (int r = 0; r < 7; r++) {
        final rowBits = rows[r];
        for (int c = 0; c < 5; c++) {
          final isOn = ((rowBits >> (4 - c)) & 1) == 1;
          final cx = offsetX + c * step + radius;
          final cy = r * step + radius;

          if (isOn) {
            canvas.drawCircle(Offset(cx, cy), radius, activePaint);
          } else if (inactivePaint != null) {
            canvas.drawCircle(Offset(cx, cy), radius * 0.65, inactivePaint);
          }
        }
      }
    }
  }

  @override
  bool shouldRepaint(covariant _DotMatrixPainter oldDelegate) =>
      oldDelegate.text != text ||
      oldDelegate.activeColor != activeColor ||
      oldDelegate.inactiveColor != inactiveColor ||
      oldDelegate.dotSize != dotSize;
}
